  // 构建繁体 -> 简体 字典
  const t2sMap = new Map();
  // 同时构建 简体 -> 繁体 字典（备用）
  const s2tMap = new Map();

  for (let i = 0; i < T2S_PAIRS.length; i++) {
    const s = T2S_PAIRS[i][0];
    const t = T2S_PAIRS[i][1];
    t2sMap.set(t, s);
    s2tMap.set(s, t);
  }

  /**
   * 将字符串中的繁体字符转换为简体字符
   * @param {string} str
   * @returns {string}
   */
  function toSimplifiedChinese(str) {
    if (!str || typeof str !== 'string') return '';
    let result = '';
    for (const char of str) {
      result += t2sMap.get(char) || char;
    }
    return result;
  }

  /**
   * 对文本进行多语言通用规范化：
   * 1. Unicode NFKC 规范化（全角英数转半角，消除日韩及符号特殊变体）
   * 2. 小写化（英文字母不区分大小写）
   * 3. 简繁统一（默认统一转简体，达成中文字简繁双向互通）
   * 4. 消除零宽字符、不可见字符干扰
   * @param {string} text
   * @param {boolean} convertTradToSimp 是否启用简繁互通转换（默认 true）
   * @returns {string}
   */
  function normalizeText(text, convertTradToSimp = true) {
    if (!text || typeof text !== 'string') return '';

    // 去除零宽字符与特殊空格
    let cleaned = text.replace(/[\u200B-\u200D\uFEFF]/g, '');

    // Unicode 规范化 + 小写处理
    cleaned = cleaned.normalize('NFKC').toLowerCase();

    // 繁体统一转简体
    if (convertTradToSimp) {
      cleaned = toSimplifiedChinese(cleaned);
    }

    return cleaned;
  }

  /**
   * 检查文本是否命中关键词列表中的任何一个
   * @param {string} rawText 待检查的文本（如帖子正文、用户名、评论）
   * @param {Array<string>} normalizedKeywords 经过规范化后的关键词数组
   * @param {Array<string>} originalKeywords 原始关键词（用于调试日志和统计）
   * @param {boolean} convertTradToSimp 是否开启简繁转换
   * @returns {{ matched: boolean, keyword: string | null }}
   */
  function checkKeywordMatch(rawText, normalizedKeywords, originalKeywords = [], convertTradToSimp = true) {
    if (!rawText || !normalizedKeywords || normalizedKeywords.length === 0) {
      return { matched: false, keyword: null };
    }

    const normText = normalizeText(rawText, convertTradToSimp);
    // 去除常见干扰符号与空格的紧凑比对串
    const compactText = normText.replace(/[\s\-_—·.,，。、!！？?~～@#$%\^&*+=]+/g, '');

    for (let i = 0; i < normalizedKeywords.length; i++) {
      const kw = normalizedKeywords[i];
      if (!kw) continue;

      if (normText.includes(kw)) {
        return {
          matched: true,
          keyword: originalKeywords[i] || kw
        };
      }

      // 对2字及以上关键词尝试去除干扰符号比对（防故意插空格防过滤）
      if (kw.length >= 2) {
        const compactKw = kw.replace(/[\s\-_—·.,，。、!！？?~～@#$%\^&*+=]+/g, '');
        if (compactKw && compactKw.length >= 2 && compactText.includes(compactKw)) {
          return {
            matched: true,
            keyword: originalKeywords[i] || kw
          };
        }
      }
    }

    return { matched: false, keyword: null };
  }

